export function fixtureClubBadgeForName(name: string): ImageSourcePropType | null {
  const canonical = canonicalClubName(name);
  const key = BADGE_ALIASES.get(canonical) ?? canonical;
  const exact = FIXTURE_BADGES.get(key);
  if (exact !== undefined) return exact;
  // A shortened feed name must identify exactly one club. In particular,
  // Dundee United must never receive Dundee's crest, nor Manchester City United's.
  const candidates = [...FIXTURE_BADGES].filter(([club]) => clubNamesMatch(club, key));
  return candidates.length === 1 ? candidates[0][1] : null;
}
